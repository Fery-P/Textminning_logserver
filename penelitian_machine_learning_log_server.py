# ============================================

def analisis_confusion_matrix(cm, kelas):

    total = cm.sum()

    hasil = []

    for i, nama_kelas in enumerate(kelas):

        # True Positive
        TP = cm[i, i]

        # False Positive
        FP = cm[:, i].sum() - TP

        # False Negative
        FN = cm[i, :].sum() - TP

        # True Negative
        TN = total - TP - FP - FN


        # Precision
        precision = TP / (TP + FP) if (TP + FP) > 0 else 0

        # Recall
        recall = TP / (TP + FN) if (TP + FN) > 0 else 0

        # F1 Score
        f1 = (
            2 * precision * recall / (precision + recall)
            if (precision + recall) > 0
            else 0
        )


        hasil.append({

            "Class": nama_kelas,

            "TP": TP,

            "FP": FP,

            "FN": FN,

            "TN": TN,

            "Precision": precision,

            "Recall": recall,

            "F1-Score": f1

        })


    return pd.DataFrame(hasil)


