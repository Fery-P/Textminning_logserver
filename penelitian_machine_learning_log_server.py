# Pola endpoint yang sering digunakan untuk probing.
# Pola ini merupakan indikator untuk pemeriksaan,
# bukan bukti bahwa request adalah serangan.

suspicious_patterns = [

    r"/\.env(?:/|$)",

    r"/wp-login\.php",

    r"/wp-admin",

    r"/wp-json/batch/v1",

    r"/administrator(?:/|$)",

    r"/admin(?:/|$)",

    r"/phpmyadmin",

    r"/\.git(?:/|$)",

    r"/\.well-known/passkey-endpoints",

]

# User-Agent monitoring yang diketahui dari
# hasil analisis awal dataset.

monitoring_patterns = [

    r"statuscake",

    r"googlebot",

    r"bingbot",

    r"ahrefsbot",

    r"semrushbot",

    r"uptimerobot",

]


# ------------------------------------------------------------
# 3. FUNGSI LABELING
# ------------------------------------------------------------

def labeling_activity(row):

    url = str(row.get("url", "")).lower()

    user_agent = str(
        row.get("user_agent", "")
    ).lower()

    http_method = str(
        row.get("http_method", "")
    ).upper()

    status_code = row.get("status_code", None)

    # --------------------------------------------------------
    # RULE 1: SUSPICIOUS ENDPOINT
    # --------------------------------------------------------

    for pattern in suspicious_patterns:

        if re.search(pattern, url):

            return pd.Series({

                "activity_label": "Suspicious",

                "label_reason":
                "Endpoint probing indicator"

            })


    # --------------------------------------------------------
    # RULE 2: MONITORING / CRAWLER
    # --------------------------------------------------------

    for pattern in monitoring_patterns:

        if re.search(pattern, user_agent):

            return pd.Series({

                "activity_label": "Monitoring_Crawler",

                "label_reason":
                "Recognized monitoring or crawler User-Agent"

            })


    # --------------------------------------------------------
    # RULE 3: REQUEST DENGAN METODE HTTP TIDAK UMUM
    # --------------------------------------------------------

    # OPTIONS dan HEAD tidak otomatis dianggap serangan.
    # Request ini hanya ditandai untuk pemeriksaan jika
    # diperlukan pada tahap validasi.

    if http_method not in [
        "GET",
        "POST",
        "HEAD",
        "OPTIONS",
        "PUT",
        "DELETE",
        "PATCH"
    ]:

        return pd.Series({

            "activity_label": "Review",

            "label_reason":
            "Unrecognized HTTP method"

        })


    # --------------------------------------------------------
    # RULE 4: REQUEST LAIN
    # --------------------------------------------------------

    return pd.Series({

        "activity_label": "Normal_candidate",

        "label_reason":
        "No predefined suspicious indicator"

    })


