import re
from urllib.parse import urlsplit, unquote

# ------------------------------------------------------------
# PREPROCESSING URL
# ------------------------------------------------------------

def preprocess_url(url):

    if pd.isna(url):
        return ""

    url = str(url).strip()

    # Decode URL
    url = unquote(url)

    # Menghapus fragment
    url = url.split("#")[0]

    # Memisahkan path dan query
    parsed = urlsplit(url)

    path = parsed.path.lower()

    query = parsed.query.lower()

    # Menggabungkan path dan query
    text = path + " " + query

    # Mengganti separator menjadi spasi
    text = re.sub(r"[/=?&._\-]+", " ", text)

    # Menghapus karakter selain huruf dan angka
    text = re.sub(r"[^a-z0-9\s]", " ", text)

    # Menghapus spasi berlebih
    text = re.sub(r"\s+", " ", text).strip()

    return text


# ------------------------------------------------------------
# PREPROCESSING USER-AGENT
# ------------------------------------------------------------

def preprocess_user_agent(user_agent):

    if pd.isna(user_agent):
        return ""

    user_agent = str(user_agent).lower()

    # Memisahkan angka dan huruf
    user_agent = re.sub(
        r"([a-z])([0-9])",
        r"\1 \2",
        user_agent
    )

    user_agent = re.sub(
        r"([0-9])([a-z])",
        r"\1 \2",
        user_agent
    )

    # Menghapus tanda baca
    user_agent = re.sub(
        r"[^a-z0-9\s]",
        " ",
        user_agent
    )

    # Menghapus spasi berlebih
    user_agent = re.sub(
        r"\s+",
        " ",
        user_agent
    ).strip()

    return user_agent


# ------------------------------------------------------------
